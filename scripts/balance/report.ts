/** Renders docs/balance/REPORT.md from the aggregated numbers. */
import type { Difficulty } from '../../src/sim/params';
import { STAGE_IDS, TRAIT_IDS, type StageId } from '../../src/sim/types';
import { SKILL_NAMES, SKILLS, type SkillName } from './skills';
import { ROWS, type CellStats, type LineageStats, type RoleStats, type Row } from './stats';
import { LIFE_COMPLETION, OFFSCREEN_SHARE_MAX, REAL, STAGE_DEATH, completionVerdict, verdict } from './targets';

export interface ReportData {
  meta: {
    seed: number;
    lives: number;
    roles: number;
    lineages: number;
    gens: number;
    workers: number;
    seconds: number;
    paramsHash: string;
    overrides: { values: Record<string, number>; mults: Record<string, number> };
    livesPlayed: number;
    simSeconds: number;
  };
  cells: CellStats[];
  roles: RoleStats[];
  lineages: LineageStats[];
}

const SUMMARY_START = '<!-- summary:start (hand-written; kept when the report is regenerated) -->';
const SUMMARY_END = '<!-- summary:end -->';

const DIFF_NAME: Record<Difficulty, string> = { fieldGuide: 'Field guide', wild: 'Wild' };
const ROW_NAME: Record<Row, string> = {
  egg: 'Egg and alevin',
  fry: 'Fry in the lake',
  smolt: 'Smolt run',
  ocean: 'Ocean years',
  'return:sea': 'Return: sea and nets',
  'return:river': 'Return: home river',
  'return:lake': 'Return: across the lake',
  spawn: 'Spawning',
};
const STAGE_NAME: Record<StageId, string> = {
  egg: 'Egg and alevin',
  fry: 'Fry',
  smolt: 'Smolt run',
  ocean: 'Ocean',
  return: 'Return',
  spawn: 'Spawning',
};

const pct = (x: number, digits = 0): string => `${(x * 100).toFixed(digits)}%`;
const pm = (x: number, ci: number): string => `${pct(x)} ±${(ci * 100).toFixed(0)}`;
const cellKey = (d: Difficulty, s: SkillName): string => `${d}/${s}`;
const mark = (v: string): string => (v === 'too easy' ? ' (easy)' : v === 'too hard' ? ' **(hard)**' : '');

function table(head: string[], rows: string[][]): string {
  return [`| ${head.join(' | ')} |`, `|${head.map((_, i) => (i === 0 ? '---' : '---:')).join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

export function renderReport(data: ReportData, previous: string): string {
  const cells = new Map(data.cells.map((c) => [cellKey(c.difficulty, c.skill), c]));
  const order: [Difficulty, SkillName][] = (['fieldGuide', 'wild'] as Difficulty[]).flatMap((d) => SKILL_NAMES.map((s) => [d, s] as [Difficulty, SkillName]));
  const cellHead = order.map(([d, s]) => `${d === 'fieldGuide' ? 'FG' : 'Wild'} ${s}`);
  const get = (d: Difficulty, s: SkillName): CellStats => {
    const c = cells.get(cellKey(d, s));
    if (!c) throw new Error(`missing cell ${d}/${s}`);
    return c;
  };
  const m = data.meta;
  const out: string[] = [];

  out.push('# Homewater balance report');
  out.push('');
  out.push(
    `Generated by \`npm run balance\` (scripts/balance/). Seed ${m.seed}; params.json sha256 \`${m.paramsHash}\`. ` +
      `${m.lives} single lives per difficulty and skill, ${m.roles} spawning trials per role, and ${m.lineages} lineages of up to ${m.gens} generations. ` +
      `${m.livesPlayed.toLocaleString('en-US')} lives in all, about ${(m.simSeconds / 3600).toFixed(0)} hours of simulated play, in ${m.seconds.toFixed(0)} s on ${m.workers} workers.`,
  );
  const ov = [...Object.entries(m.overrides.values).map(([k, v]) => `${k} = ${v}`), ...Object.entries(m.overrides.mults).map(([k, v]) => `${k} multiplier ${v}`)];
  if (ov.length) out.push('', `**What-if run** with overrides: ${ov.join(', ')}.`);
  out.push('');
  out.push('How to read it:');
  out.push('- **Per-fish death rate:** the share of attempts at a stage that end in death. A sibling resuming at a checkpoint is a new attempt.');
  out.push('- **Brood:** the first fish plus its siblings (siblings param + 1). The brood fails when the last fish dies.');
  out.push('- **Bots:** play through the public World API with Intent inputs only, reading what is on screen. Novice, average and skilled differ in reaction time, steering wobble, missed threats, attention lapses and habits; see `scripts/balance/skills.ts`.');
  out.push('- **Marks:** (easy) and **(hard)** compare against the design bands in `scripts/balance/targets.ts`, which are the simulator\'s proposal for the owner to confirm.');
  out.push('- **±** is a 95% interval.');
  out.push('');

  // Hand-written summary, kept across runs.
  const i0 = previous.indexOf(SUMMARY_START);
  const i1 = previous.indexOf(SUMMARY_END);
  out.push(SUMMARY_START);
  if (i0 >= 0 && i1 > i0) out.push(previous.slice(i0 + SUMMARY_START.length, i1).trim());
  else out.push('## Summary\n\n_Not written yet._');
  out.push(SUMMARY_END);
  out.push('');

  // Key numbers.
  out.push('## Key numbers');
  out.push('');
  out.push(
    table(
      ['', 'Brood', 'Life completed', 'First fish spawns', 'Siblings used', 'Play time (completed)', 'Jacks / males'],
      order.map(([d, s]) => {
        const c = get(d, s);
        const v = completionVerdict(c.completion, LIFE_COMPLETION[d][s]);
        return [
          `${DIFF_NAME[d]}, ${s}`,
          String(c.brood),
          `${pm(c.completion, c.completionCi)}${mark(v)}`,
          pct(c.firstFishCompletion),
          `${c.siblingsUsedMean.toFixed(2)} (${c.siblingsUsedCompletedMean.toFixed(2)})`,
          `${(c.playSecondsCompletedMean / 60).toFixed(1)} min`,
          `${pct(c.jackShareOfMales, 1)} of ${c.malesMatured}`,
        ];
      }),
    ),
  );
  out.push('');
  out.push('Siblings used: mean over all lives (and over completed lives). Jacks / males: males that reached maturation.');
  out.push('');

  // Per-stage death rates.
  out.push('## Per-fish death rate by stage');
  out.push('');
  out.push(
    table(
      ['Stage', ...cellHead],
      ROWS.map((r) => [
        ROW_NAME[r],
        ...order.map(([d, s]) => {
          const st = get(d, s).stages[r];
          return `${pct(st.rate)}${mark(verdict(st.rate, STAGE_DEATH[d][s]))}`;
        }),
      ]),
    ),
  );
  out.push('');
  out.push(
    `Bands (per stage): ${(['fieldGuide', 'wild'] as Difficulty[])
      .map((d) => `${DIFF_NAME[d]} ${SKILL_NAMES.map((s) => `${s} ${pct(STAGE_DEATH[d][s].min)}-${pct(STAGE_DEATH[d][s].max)}`).join(', ')}`)
      .join('; ')}.`,
  );
  out.push('');

  out.push('### Causes of death');
  out.push('');
  out.push(
    table(
      ['Stage', ...cellHead],
      ROWS.map((r) => [
        ROW_NAME[r],
        ...order.map(([d, s]) => {
          const st = get(d, s).stages[r];
          const total = Object.values(st.causes).reduce((a, b) => a + b, 0);
          if (!total) return '-';
          return Object.entries(st.causes)
            .sort((a, b) => b[1] - a[1])
            .slice(0, 3)
            .map(([c, k]) => `${c} ${pct(k / st.attempts)}`)
            .join(', ');
        }),
      ]),
    ),
  );
  out.push('');
  out.push('Shares are of attempts. `sea` is the off-screen roll for each extra year at sea; `noSpawn` is a spawning stage that ends without spawning.');
  out.push('');
  out.push(
    table(
      ['', ...cellHead],
      [
        ['Attempts per stage (smolt)', ...order.map(([d, s]) => String(get(d, s).stages.smolt.attempts))],
        [
          'Off-screen share of all deaths',
          ...order.map(([d, s]) => {
            const v = get(d, s).offscreenShare;
            return `${pct(v)}${v > OFFSCREEN_SHARE_MAX ? ' **(high)**' : ''}`;
          }),
        ],
        ['Ocean deaths that are the off-screen roll', ...order.map(([d, s]) => pct(get(d, s).oceanSeaShare))],
        ['Lives stopped by a stuck bot', ...order.map(([d, s]) => String(get(d, s).timeouts))],
      ],
    ),
  );
  out.push('');

  // Brood loss.
  out.push('## Chance the whole brood is lost at each stage');
  out.push('');
  out.push(
    table(
      ['Stage', ...cellHead],
      [
        ...STAGE_IDS.map((st) => [STAGE_NAME[st], ...order.map(([d, s]) => pct(get(d, s).broodLoss[st], 1))]),
        ['**Any stage**', ...order.map(([d, s]) => `**${pct(1 - get(d, s).completion, 1)}**`)],
      ],
    ),
  );
  out.push('');
  out.push('Out of all lives. On Field guide a lost brood brings in a stray; on Wild the line ends.');
  out.push('');

  // Durations.
  out.push('## Stage length (seconds of play)');
  out.push('');
  out.push(
    table(
      ['Stage', ...cellHead],
      [
        ...STAGE_IDS.map((st) => [STAGE_NAME[st], ...order.map(([d, s]) => get(d, s).seconds[st].ok.toFixed(0))]),
        ['**Whole life (completed)**', ...order.map(([d, s]) => `**${(get(d, s).playSecondsCompletedMean / 60).toFixed(1)} min**`)],
        ['Whole life (all lives)', ...order.map(([d, s]) => `${(get(d, s).playSecondsMean / 60).toFixed(1)} min`)],
      ],
    ),
  );
  out.push('');
  out.push('Mean length of a successful attempt from the stage start. Whole life includes every sibling\'s attempts.');
  out.push('');

  // Game vs real.
  out.push('## Game odds beside the advisor\'s figures');
  out.push('');
  const surv = (c: CellStats, rows: Row[]): number => rows.reduce((a, r) => a * (1 - c.stages[r].rate), 1);
  const realRow = (label: string, real: string, rows: Row[]): string[] => [label, real, ...order.map(([d, s]) => pct(surv(get(d, s), rows), 0))];
  out.push(
    table(
      ['One fish survives', 'Real', ...cellHead],
      [
        realRow('Egg to emergence', `${pct(REAL.eggToEmergence.min)}-${pct(REAL.eggToEmergence.max)}`, ['egg']),
        ['Egg to emergence, brood-mates in the nest (seen, not played)', `${pct(REAL.eggToEmergence.min)}-${pct(REAL.eggToEmergence.max)}`, ...order.map(([d, s]) => pct(get(d, s).broodEmerged, 0))],
        realRow('Fry to leaving the lake', `${pct(REAL.fryToSmolt.min)}-${pct(REAL.fryToSmolt.max)}`, ['fry']),
        realRow('Marine (smolt run, ocean, return at sea)', `about ${pct(REAL.marine.min)}`, ['smolt', 'ocean', 'return:sea']),
        realRow('Egg to spawning', 'well under 1%', [...ROWS]),
      ],
    ),
  );
  out.push('');
  out.push(
    `Jacks among males that matured: real 1-2% of males in a typical run; creek base rate in params ${pct(0.04)}. ` +
      `Two measures, from the single lives: the share of maturation decisions that came out jack (every male that finished feeding at sea, siblings included), and the share of jacks among the males the player went on to play upstream.`,
  );
  out.push('');
  out.push(
    table(
      ['', ...cellHead],
      [
        ['Jack per maturation decision', ...order.map(([d, s]) => `${pct(get(d, s).jackPerDecision, 1)} of ${get(d, s).decisions}`)],
        ['Jacks among males played upstream', ...order.map(([d, s]) => `${pct(get(d, s).jackShareOfMales, 1)} of ${get(d, s).malesMatured}`)],
      ],
    ),
  );
  out.push('');

  // Spawning roles.
  out.push('## Spawning by role');
  out.push('');
  out.push(`Separate trials that start at the spawning grounds (${m.roles} per cell), with no siblings, so each role is measured on its own.`);
  out.push('');
  const roleRows: string[][] = [];
  for (const role of ['female', 'largeMale', 'jack']) {
    roleRows.push([
      role,
      ...order.map(([d, s]) => {
        const r = data.roles.find((x) => x.difficulty === d && x.skill === s && x.role === role);
        if (!r || !r.n) return '-';
        const top = Object.entries(r.causes)
          .sort((a, b) => b[1] - a[1])
          .slice(0, 2)
          .map(([c, k]) => `${c} ${pct(k / r.n)}`)
          .join(', ');
        return `${pct(r.spawned / r.n)} spawn, ${r.fitnessMean.toFixed(2)}x${top ? `; ${top}` : ''}`;
      }),
    ]);
  }
  out.push(table(['Role', ...cellHead], roleRows));
  out.push('');
  out.push('Spawn rate, mean relative fitness of those that spawned (1.0 = an average spawner), and the main ways it failed.');
  out.push('');

  // Lineages.
  out.push('## Generations');
  out.push('');
  out.push(`${m.lineages} lineages per cell, up to ${m.gens} generations, offspring picked at random from the three offered.`);
  out.push('');
  out.push(
    table(
      ['', 'Generations played', `Lines alive at gen ${Math.min(5, m.gens)}`, `at gen ${m.gens}`, 'Lives completed', 'Stray lives', 'Jacks / males'],
      order.map(([d, s]) => {
        const l = data.lineages.find((x) => x.difficulty === d && x.skill === s);
        if (!l) return [`${DIFF_NAME[d]}, ${s}`, '-', '-', '-', '-', '-', '-'];
        const comp = l.completionByGen.reduce((a, b) => a + b, 0) / Math.max(1, l.completionByGen.length);
        return [
          `${DIFF_NAME[d]}, ${s}`,
          l.meanGenerationsPlayed.toFixed(1),
          pct(l.alive[Math.min(5, m.gens) - 1] ?? 0),
          pct(l.alive[m.gens - 1] ?? 0),
          pct(comp),
          pct(l.strayRate),
          `${pct(l.jackShareOfMales, 1)} of ${l.malesMatured}`,
        ];
      }),
    ),
  );
  out.push('');
  out.push('Trait drift: mean breeding value of the played fish, first generation to last (population mean 0, SD about 0.6).');
  out.push('');
  out.push(
    table(
      ['Trait', ...cellHead],
      TRAIT_IDS.map((t) => [
        t,
        ...order.map(([d, s]) => {
          const l = data.lineages.find((x) => x.difficulty === d && x.skill === s);
          if (!l) return '-';
          const series = l.bvByGen[t];
          const last = [...series].reverse().find((_, i) => (l.alive[series.length - 1 - i] ?? 0) > 0) ?? 0;
          return `${(series[0] ?? 0).toFixed(2)} → ${last.toFixed(2)}`;
        }),
      ]),
    ),
  );
  out.push('');

  // Automatic flags.
  out.push('## Automatic flags');
  out.push('');
  const flags: string[] = [];
  for (const [d, s] of order) {
    const c = get(d, s);
    for (const r of ROWS) {
      const st = c.stages[r];
      const v = verdict(st.rate, STAGE_DEATH[d][s]);
      if (v !== 'in band' && st.attempts >= 20) flags.push(`${DIFF_NAME[d]}, ${s}: ${ROW_NAME[r]} is ${v} (${pct(st.rate)} per fish; band ${pct(STAGE_DEATH[d][s].min)}-${pct(STAGE_DEATH[d][s].max)}).`);
    }
    const v = completionVerdict(c.completion, LIFE_COMPLETION[d][s]);
    if (v !== 'in band') flags.push(`${DIFF_NAME[d]}, ${s}: whole life is ${v} (${pct(c.completion)} completed; band ${pct(LIFE_COMPLETION[d][s].min)}-${pct(LIFE_COMPLETION[d][s].max)}).`);
    if (c.offscreenShare > OFFSCREEN_SHARE_MAX) flags.push(`${DIFF_NAME[d]}, ${s}: ${pct(c.offscreenShare)} of deaths are off-screen rolls (more than ${pct(OFFSCREEN_SHARE_MAX)}).`);
    if (c.timeouts) flags.push(`${DIFF_NAME[d]}, ${s}: ${c.timeouts} lives stopped by a stuck bot (bot issue, not a game result).`);
  }
  out.push(flags.length ? flags.map((f) => `- ${f}`).join('\n') : '_None._');
  out.push('');

  out.push('## Bot profiles');
  out.push('');
  out.push(
    table(
      ['Skill', 'Reaction', 'Steering wobble', 'Misses a threat', 'Lapses', 'Steering', 'Habits'],
      SKILL_NAMES.map((s) => {
        const k = SKILLS[s];
        const habits = [
          k.earlyRiseChance ? `rises early ${pct(k.earlyRiseChance)}` : '',
          Number.isFinite(k.fryBurstDist) ? '' : 'bursts at first sight',
          k.panicChance ? `flees straight ${pct(k.panicChance)}` : '',
          `smolt depth ${-k.smoltDepth}`,
          k.sealSprint ? 'sprints past seals' : '',
          k.estuaryPatience ? `holds in the estuary to ${pct(k.estuaryPatience)} ready` : 'rushes the estuary',
          `feeds rich at sea ${pct(k.oceanBold)}${k.oceanWary ? ', moves off when a hunter shows' : ''}`,
          k.forkMistake ? `wrong fork ${pct(k.forkMistake)}` : '',
          k.riverBurst ? 'bursts upstream' : '',
          k.bankSwim ? 'swims the slow edges' : '',
          k.defendEarly ? 'guards the redd early' : '',
          k.sideOn ? 'rams side-on' : 'rams head-on',
        ].filter(Boolean);
        return [
          s,
          `${k.reaction.toFixed(2)} s`,
          `${k.steerNoise.toFixed(2)} rad`,
          pct(k.missChance),
          k.lapseRate ? `every ${(1 / k.lapseRate).toFixed(0)} s, ${k.lapseDur} s` : 'none',
          k.mouse ? `mouse, ${k.maxTurnRate} rad/s` : 'keyboard',
          habits.join('; '),
        ];
      }),
    ),
  );
  out.push('');
  return `${out.join('\n')}\n`;
}
